    ("pasta", ["pasta", "spaghetti", "noodles", "pad-thai", "zoodles", "carbonara", "alfredo", "mac-and-cheese", "lasagna", "spaetzle", "stroganoff"]),
    ("bowl", ["bowl", "fried-rice", "soup", "stew", "chili", "curry", "dal", "risotto", "chowder", "bisque", "pozole", "feijoada", "moqueca", "tikka", "butter-chicken", "mapo", "dip", "hummus", "guacamole", "fondue", "mousse", "pudding", "panna-cotta", "creme-brulee", "granola"]),
    ("salad", ["salad", "caprese", "vegetable", "stuffed-bell-peppers", "stuffed-peppers", "stuffed-mushrooms"]),
    ("sandwich", ["grilled-cheese", "sliders", "burger", "pulled-chicken", "bratwurst", "currywurst"]),
